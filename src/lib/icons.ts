/** Sugere um ícone a partir do nome da categoria. */
export function suggestIcon(name: string): string {
  const n = normalize(name);
  if (!n) return "Tag";
  for (const [keywords, icon] of KEYWORD_ICONS) {
    if (keywords.some((k) => n.includes(k))) return icon;
  }
  return "Tag";
}
