const ICONS_BY_NAME: Record<string, LucideIcon> = Object.fromEntries(
  ICONS.map((i) => [i.name, i.Icon]),
);

/** Retorna o componente do ícone, com fallback para Tag. */
export function getCategoryIcon(name?: string | null): LucideIcon {
  if (name && ICONS_BY_NAME[name]) return ICONS_BY_NAME[name] ?? Tag;
  return Tag;
}

const normalize = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim();

